'use strict';

// Browser-readable data generated from the reviewed JSON (no runtime fetch).
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'pricing/master-2026-09.json'), 'utf8'));
const output = '// Generated by scripts/build-price-context.cjs; edit master-2026-09.json instead.\n' +
  'var USGlassApprovedMaster = ' + JSON.stringify(data, null, 2) + ';\n';
const target = path.join(root, 'pricing/approved-master.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Run node scripts/build-price-context.cjs');
} else {
  fs.writeFileSync(target, output);
}
